// Standard (not URL-safe) base64 of a byte array, the encoding the Worker's JSON
// bodies use for a small file -- e.g. an inline link favicon. Built in chunks
// because String.fromCharCode(...bytes) throws a RangeError past the engine's
// argument limit, which a large favicon could reach.
const CHUNK_SIZE = 0x8000;

/** @param {Uint8Array} bytes */
export function bytesToBase64(bytes) {
  let binary = "";
  for (let i = 0; i < bytes.length; i += CHUNK_SIZE) {
    binary += String.fromCharCode(...bytes.subarray(i, i + CHUNK_SIZE));
  }
  return btoa(binary);
}
